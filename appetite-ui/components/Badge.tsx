// Why: Badge labels or flags something (a count, a status, an unread mark) and is not interactive. State
// is a color tone here (Error, Success, ...), not an interaction state, and keeps its Figma name so a
// Dev Mode selection maps to props one to one (docs/inventory.md, CHECK note).
// Figma: Badge 125:1750 (60 variants: State x Type x Style, plus a Label text and a Dot boolean),
// read 3 Oct 2026.
// Numbers it relies on:
// - Type=Pill: hugs its label. Padding spacing/1 (4) vertical, spacing/2-5 (10) horizontal, gap
//   spacing/1-5 (6), radius full, height 24 = 4 + the 16 pt line + 4. Label text style xs/emphasized
//   (Inter 600 12/16, tracking 0.1) in a HugText (Figma rounds the label box up to whole points).
// - Dot=True (Pill only): Figma's hidden 6 x 6 ellipse "Dot" (visible bound to the Dot property) sits
//   before the label with the same 6 pt gap; hidden, it takes no space. Fill: text/on-color/strong on
//   Style=Color, state/<tone>/base-500 on Style=Soft.
// - Type=Circle: padding spacing/0-5 (2), centered label, 20 x 20 = 2 + 16 + 2. Figma fixes the width at 20
//   and hugs the height; code makes the width at least the height so a label wider than 20 pt grows into
//   a capsule instead of clipping (Figma does not define that case).
// - Label placement: Figma's "Text Wrapper" is a 16 pt line box (the xs line height) around the label. Code
//   builds the same box and drops the label's own lineHeight so the box centers the natural-height text.
//   Measured on the iPhone 18 Pro simulator over 64 targets: with lineHeight 16 set on the label, React
//   Native puts the glyphs 2 px (at 3x) lower than Figma and 32 targets failed parity; with the line box
//   the offset is 1 px and 53 of 64 pass.
// - Type=Dot: 6 x 6, bound to spacing/1-5 on both axes, no label.
// - Colors per Style x State: the TONES table below, every entry a Color Tokens variable. Soft: fill
//   state/<tone>/lighter-50, text state/<tone>/dark-950. Color: fill state/<tone>/base-500, text
//   text/on-color/strong. Neutral is state/faded/*. Type=Dot differs: Soft fill is state/<tone>/light-200
//   and Color fill state/<tone>/base-500, except Neutral, which binds bg/soft-100 and bg/strong-950.
// - Style=Color links the Figma effect style dropShadow/xs (styles.effect on all 30 Color variants):
//   0 1 2 at 4 % black and 0 4 4 at 1 % black. Effect styles have no variables, so the value comes from
//   shared/effects.ts (generated by scripts/figma/effects.mjs).
// Known Figma inconsistency, not copied: State=Error, Type=Circle, Style=Color (125:1945) has padding-left
// 0 where the other 19 circles have 2, which would put its label 1 pt left of center. Code centers it.
// Platform: the same on iOS and Material (the Figma component has no Platform mode difference). Not
// interactive, so no hit area, no pressed state.
import type { ReactElement } from 'react';
import { View, type StyleProp, type ViewStyle } from 'react-native';
import type { AppetiteTokens } from '@appetite-ui/tokens';
import { useAppetiteTheme } from '@appetite-ui/core';
import { makeStyles } from '@appetite-ui/core';
import { textStyle } from '@appetite-ui/core';
import { HugText } from '../shared/HugText';
import { FONT_SCALE_CAP, dropShadow } from '@appetite-ui/core/internal';

/** Figma property State. A color tone, not an interaction state. */
export type BadgeState = 'error' | 'neutral' | 'information' | 'warning' | 'away' | 'success' | 'feature' | 'verified' | 'highlighted' | 'stable';
/** Figma property Type. */
export type BadgeType = 'pill' | 'circle' | 'dot';
/** Figma property Style (React Native reserves `style`). */
export type BadgeVariant = 'soft' | 'color';

interface BadgeCommonProps {
  /** Figma State, a color tone. Default "neutral" (the Figma default). */
  state?: BadgeState;
  /** Figma Style. Default "soft" (the Figma default). */
  variant?: BadgeVariant;
  /** Layout only (margins, alignSelf). Colors come from the props. */
  style?: StyleProp<ViewStyle>;
  testID?: string;
}

interface BadgePillProps extends BadgeCommonProps {
  /** Figma Type. Default "pill" (the Figma default). */
  type?: 'pill';
  /** Figma Label. */
  label: string;
  /** Figma Dot (Pill only): a small dot before the label. Default false. */
  dot?: boolean;
  /** Defaults to label. */
  accessibilityLabel?: string;
}

interface BadgeCircleProps extends BadgeCommonProps {
  /** Figma Type=Circle: a round badge for a short count. */
  type: 'circle';
  /** Figma Label. Keep it to one or two characters: a longer label grows the circle into a capsule. */
  label: string;
  /** Defaults to label. */
  accessibilityLabel?: string;
}

interface BadgeDotProps extends BadgeCommonProps {
  /** Figma Type=Dot: a 6 pt dot with no label. */
  type: 'dot';
  /** Required: a dot has no visible text, so its meaning ("Unread", "Online") must be spoken. */
  accessibilityLabel: string;
}

export type BadgeProps = BadgePillProps | BadgeCircleProps | BadgeDotProps;

type ColorToken = keyof AppetiteTokens['colors'];

interface Tone {
  /** Style=Soft fill of Pill and Circle. */
  softFill: ColorToken;
  /** Style=Soft label color, and nothing else. */
  softText: ColorToken;
  /** Style=Color fill of Pill and Circle; also the Soft Dot of the Pill (Dot=True). */
  base: ColorToken;
  /** Type=Dot, Style=Soft. */
  dotSoft: ColorToken;
  /** Type=Dot, Style=Color. */
  dotColor: ColorToken;
}

// Read from the Pill, Circle and Dot variants of every State (docs/inventory.md row 13).
const TONES: Record<BadgeState, Tone> = {
  neutral: { softFill: 'stateFadedLighter50', softText: 'stateFadedDark950', base: 'stateFadedBase500', dotSoft: 'bgSoft100', dotColor: 'bgStrong950' },
  information: { softFill: 'stateInformationLighter50', softText: 'stateInformationDark950', base: 'stateInformationBase500', dotSoft: 'stateInformationLight200', dotColor: 'stateInformationBase500' },
  error: { softFill: 'stateErrorLighter50', softText: 'stateErrorDark950', base: 'stateErrorBase500', dotSoft: 'stateErrorLight200', dotColor: 'stateErrorBase500' },
  warning: { softFill: 'stateWarningLighter50', softText: 'stateWarningDark950', base: 'stateWarningBase500', dotSoft: 'stateWarningLight200', dotColor: 'stateWarningBase500' },
  away: { softFill: 'stateAwayLighter50', softText: 'stateAwayDark950', base: 'stateAwayBase500', dotSoft: 'stateAwayLight200', dotColor: 'stateAwayBase500' },
  success: { softFill: 'stateSuccessLighter50', softText: 'stateSuccessDark950', base: 'stateSuccessBase500', dotSoft: 'stateSuccessLight200', dotColor: 'stateSuccessBase500' },
  feature: { softFill: 'stateFeatureLighter50', softText: 'stateFeatureDark950', base: 'stateFeatureBase500', dotSoft: 'stateFeatureLight200', dotColor: 'stateFeatureBase500' },
  verified: { softFill: 'stateVerifiedLighter50', softText: 'stateVerifiedDark950', base: 'stateVerifiedBase500', dotSoft: 'stateVerifiedLight200', dotColor: 'stateVerifiedBase500' },
  highlighted: { softFill: 'stateHighlightedLighter50', softText: 'stateHighlightedDark950', base: 'stateHighlightedBase500', dotSoft: 'stateHighlightedLight200', dotColor: 'stateHighlightedBase500' },
  stable: { softFill: 'stateStableLighter50', softText: 'stateStableDark950', base: 'stateStableBase500', dotSoft: 'stateStableLight200', dotColor: 'stateStableBase500' },
};

const useStyles = makeStyles(({ tokens: t }) => ({
  base: { alignSelf: 'flex-start', borderRadius: t.shapes.full },
  pill: {
    flexDirection: 'row',
    alignItems: 'center',
    gap: t.spacing.space1_5,
    paddingVertical: t.spacing.space1,
    paddingHorizontal: t.spacing.space2_5,
  },
  // Figma: width fixed at 20, height hugs 2 + 16 + 2. minWidth = that height keeps it a circle.
  circle: {
    alignItems: 'center',
    justifyContent: 'center',
    padding: t.spacing.space0_5,
    height: 2 * t.spacing.space0_5 + t.type.lineHeight.xs,
    minWidth: 2 * t.spacing.space0_5 + t.type.lineHeight.xs,
  },
  // Figma's "Text Wrapper": a line box as tall as the xs line (16) that holds the label. The label drops its
  // own lineHeight so the box centers the natural-height text, which is where Figma puts the baseline. With
  // lineHeight set, React Native on iOS puts the glyphs 2 px (at 3x) lower than Figma (measured, see log).
  lineBox: { height: t.type.lineHeight.xs, justifyContent: 'center' },
  label: { lineHeight: undefined },
  dot: { width: t.spacing.space1_5, height: t.spacing.space1_5 },
  pillDot: { width: t.spacing.space1_5, height: t.spacing.space1_5, borderRadius: t.shapes.full },
}));

export function Badge(props: BadgeProps): ReactElement {
  const { tokens: t } = useAppetiteTheme();
  const styles = useStyles();
  const { state = 'neutral', variant = 'soft', style, testID } = props;
  const tone = TONES[state];
  const soft = variant === 'soft';
  const shadow: ViewStyle = soft ? {} : { boxShadow: dropShadow.xs };

  if (props.type === 'dot') {
    return (
      <View
        testID={testID}
        accessible
        accessibilityRole="image"
        accessibilityLabel={props.accessibilityLabel}
        style={[styles.base, styles.dot, { backgroundColor: t.colors[soft ? tone.dotSoft : tone.dotColor] }, shadow, style]}
      />
    );
  }

  const isCircle = props.type === 'circle';
  const dot = !isCircle && props.dot === true;
  return (
    <View
      testID={testID}
      accessible
      accessibilityRole="text"
      accessibilityLabel={props.accessibilityLabel ?? props.label}
      style={[styles.base, isCircle ? styles.circle : styles.pill, { backgroundColor: t.colors[soft ? tone.softFill : tone.base] }, shadow, style]}
    >
      {dot && <View style={[styles.pillDot, { backgroundColor: t.colors[soft ? tone.base : 'textOnColorStrong'] }]} />}
      <View style={styles.lineBox}>
        <HugText numberOfLines={1} maxFontSizeMultiplier={FONT_SCALE_CAP.badge} style={[textStyle(t, 'xs/emphasized'), styles.label, { color: t.colors[soft ? tone.softText : 'textOnColorStrong'] }]}>
          {props.label}
        </HugText>
      </View>
    </View>
  );
}
